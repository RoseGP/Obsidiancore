type Tone = 'neutral' | 'success' | 'warning' | 'danger' | 'info' | 'accent';
const TONE: Record<Tone, string> = {
  neutral: 'bg-[var(--surface-sunken)] text-[var(--text-muted)]', success: 'bg-[var(--success-soft)] text-[var(--success)]', warning: 'bg-[var(--warning-soft)] text-[var(--warning)]',
  danger: 'bg-[var(--danger-soft)] text-[var(--danger)]', info: 'bg-[var(--info-soft)] text-[var(--info)]', accent: 'bg-[var(--accent-soft)] text-[var(--accent-text)]',
};
export const Badge = ({ tone = 'neutral', children, className, title }: { tone?: Tone; children: React.ReactNode; className?: string; title?: string }) => (
  <span title={title} className={cx('inline-flex items-center gap-1 rounded-full px-2 py-0.5 text-[12px] font-medium whitespace-nowrap', TONE[tone], className)}>{children}</span>
);

export const scoreTone = (s: number): Tone => (s >= 80 ? 'success' : s >= 55 ? 'warning' : 'danger');
export function ScoreRing({ score, size = 64, label }: { score: number; size?: number; label?: string }) {
  const r = size / 2 - 5; const c = 2 * Math.PI * r; const tone = scoreTone(score);
  return (
    <div className="relative inline-flex items-center justify-center" style={{ width: size, height: size }} role="img" aria-label={`${label ?? 'Score'} ${score} out of 100`}>
      <svg width={size} height={size} className="-rotate-90">
        <circle cx={size / 2} cy={size / 2} r={r} fill="none" stroke="var(--surface-sunken)" strokeWidth={6} />
        <circle cx={size / 2} cy={size / 2} r={r} fill="none" stroke={`var(--${tone})`} strokeWidth={6} strokeLinecap="round" strokeDasharray={c} strokeDashoffset={c * (1 - score / 100)} />
      </svg>
      <span className="absolute text-[var(--text)] font-semibold tabular-nums" style={{ fontSize: size * 0.28 }}>{score}</span>
    </div>
  );
}

export function Meter({ value, tone }: { value: number; tone?: Tone }) {
  const t = tone ?? scoreTone(value);
  return <div className="h-1.5 w-full rounded-full bg-[var(--surface-sunken)] overflow-hidden" role="meter" aria-valuenow={value} aria-valuemin={0} aria-valuemax={100}><div className="h-full rounded-full" style={{ width: `${value}%`, background: `var(--${t})` }} /></div>;
}

