export function timeAgo(iso?: string): string {
  if (!iso) return 'never';
  const s = Math.round((Date.now() - Date.parse(iso)) / 1000);
  if (s < 60) return 'just now';
  const m = Math.round(s / 60); if (m < 60) return `${m} min ago`;
  const h = Math.round(m / 60); if (h < 24) return `${h} h ago`;
  const d = Math.round(h / 24); if (d < 30) return `${d} day${d === 1 ? '' : 's'} ago`;
  return new Date(iso).toLocaleDateString(undefined, { year: 'numeric', month: 'short', day: 'numeric' });
}

// ---- Toasts ----
type ToastT = { id: number; tone: 'success' | 'danger' | 'info'; text: string };
const ToastCtx = createContext<(text: string, tone?: ToastT['tone']) => void>(() => undefined);
export function ToastProvider({ children }: { children: React.ReactNode }) {
  const [items, setItems] = useState<ToastT[]>([]);
  const push = useCallback((text: string, tone: ToastT['tone'] = 'success') => {
    const id = Date.now() + Math.random();
    setItems((x) => [...x.slice(-2), { id, tone, text }]);
    setTimeout(() => setItems((x) => x.filter((t) => t.id !== id)), tone === 'danger' ? 7000 : 4000);
  }, []);
  return (
    <ToastCtx.Provider value={push}>
      {children}
      <div className="fixed bottom-24 right-6 z-[210] flex flex-col gap-2 w-[min(380px,calc(100vw-2rem))]" aria-live="polite">
        {items.map((t) => <div key={t.id} className="shadow-[var(--shadow-lg)] rounded-[var(--radius-control)] bg-[var(--surface)]"><Notice tone={t.tone} title={t.text} /></div>)}
      </div>
    </ToastCtx.Provider>
  );
}
export const useToast = () => useContext(ToastCtx);
