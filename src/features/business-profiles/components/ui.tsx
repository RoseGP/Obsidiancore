export const cx = (...c: (string | false | null | undefined)[]) => c.filter(Boolean).join(' ');

export function Button({ variant = 'secondary', size = 'md', loading, icon, children, className, ...p }: React.ButtonHTMLAttributes<HTMLButtonElement> & { variant?: 'primary' | 'secondary' | 'ghost' | 'danger'; size?: 'sm' | 'md'; loading?: boolean; icon?: React.ReactNode }) {
  const v = {
    primary: 'bg-[var(--accent)] text-[var(--accent-contrast,#fff)] hover:bg-[var(--accent-hover)] border border-transparent',
    secondary: 'bg-[var(--surface)] text-[var(--text)] border border-[var(--border-strong)] hover:bg-[var(--surface-sunken)]',
    ghost: 'bg-transparent text-[var(--text-muted)] hover:text-[var(--text)] hover:bg-[var(--surface-sunken)] border border-transparent',
    danger: 'bg-[var(--danger)] text-white hover:opacity-90 border border-transparent',
  }[variant];
  return (
    <button type="button" {...p} disabled={p.disabled || loading}
      className={cx('inline-flex items-center justify-center gap-1.5 whitespace-nowrap rounded-[var(--radius-control)] font-medium transition-colors focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-[var(--focus-ring,var(--accent))] disabled:opacity-50 disabled:cursor-not-allowed', size === 'sm' ? 'h-8 px-2.5 text-[13px]' : 'h-9 px-3.5 text-sm', v, className)}>
      {loading ? <Loader2 className="h-4 w-4 animate-spin" aria-hidden /> : icon}{children}
    </button>
  );
}

