export function Modal({ open, title, onClose, children, footer, wide }: { open: boolean; title: string; onClose: () => void; children: React.ReactNode; footer?: React.ReactNode; wide?: boolean }) {
  const ref = useRef<HTMLDivElement>(null);
  useEffect(() => {
    if (!open) return;
    const prev = document.activeElement as HTMLElement | null;
    ref.current?.focus();
    const onKey = (e: KeyboardEvent) => { if (e.key === 'Escape') onClose(); };
    window.addEventListener('keydown', onKey);
    return () => { window.removeEventListener('keydown', onKey); prev?.focus?.(); };
  }, [open, onClose]);
  if (!open) return null;
  return (
    <div className="fixed inset-0 z-[200] flex items-center justify-center bg-black/40 p-4" onMouseDown={(e) => { if (e.target === e.currentTarget) onClose(); }}>
      <div ref={ref} tabIndex={-1} role="dialog" aria-modal="true" aria-label={title} className={cx('w-full max-h-[90vh] overflow-auto bg-[var(--surface-raised,var(--surface))] border border-[var(--border)] rounded-[var(--radius-panel)] shadow-[var(--shadow-xl)] focus:outline-none', wide ? 'max-w-3xl' : 'max-w-lg')}>
        <div className="flex items-center justify-between px-5 py-4 border-b border-[var(--border)]">
          <h2 className="text-base font-semibold text-[var(--text)]">{title}</h2>
          <button onClick={onClose} className="p-1 rounded text-[var(--text-muted)] hover:bg-[var(--surface-sunken)]" aria-label="Close"><X className="h-4 w-4" /></button>
        </div>
        <div className="px-5 py-4 text-sm text-[var(--text)]">{children}</div>
        {footer && <div className="flex justify-end gap-2 px-5 py-3 border-t border-[var(--border)]">{footer}</div>}
      </div>
    </div>
  );
}

export function Notice({ tone = 'info', title, children, action }: { tone?: Tone; title?: string; children?: React.ReactNode; action?: React.ReactNode }) {
  const Icon = tone === 'danger' ? XCircle : tone === 'warning' ? AlertTriangle : tone === 'success' ? CheckCircle2 : Info;
  return (
    <div className={cx('flex gap-3 rounded-[var(--radius-control)] p-3 text-[13px]', TONE[tone])} role={tone === 'danger' ? 'alert' : 'status'}>
      <Icon className="h-4 w-4 mt-0.5 shrink-0" aria-hidden />
      <div className="flex-1 min-w-0 text-[var(--text)]">{title && <div className="font-medium">{title}</div>}{children && <div className="text-[var(--text-muted)] mt-0.5">{children}</div>}</div>
      {action}
    </div>
  );
}

